function _canonicalLanguage(value) {
  const normalized = String(value || '').trim().toLowerCase();
  return [...KNOWN_LANGUAGES].find(language => language.toLowerCase() === normalized) || '';
}

function _browserRegion() {
  const locale = globalThis.navigator?.language || '';
  if (!locale) return '';
  try {
    return new Intl.Locale(locale).maximize().region || '';
  } catch {
    return String(locale).match(/[-_]([A-Za-z]{2}|[0-9]{3})(?:$|-)/)?.[1]?.toUpperCase() || '';
  }
}

function _dispatch(name, detail) {
  if (typeof window === 'undefined' || typeof CustomEvent === 'undefined') return;
  window.dispatchEvent(new CustomEvent(name, { detail }));
}

function _replace(template, values = {}) {
  return String(template).replace(
    /\{([a-z0-9_]+)\}/gi,
    (_match, name) => String(values[name] ?? ''),
  );
}

function _validCatalog(catalog, language) {
  return catalog?.schema_version === 1
    && catalog?.language === language
    && catalog?.messages
    && typeof catalog.messages === 'object'
    && catalog?.plurals
    && typeof catalog.plurals === 'object';
}

export function installCatalog(catalog) {
  const language = _canonicalLanguage(catalog?.language);
  if (!language || !_validCatalog(catalog, language)) throw new Error('invalid localization catalog');
  CATALOGS.set(language, catalog);
  return catalog;
}

export async function loadCatalog(language, fetcher = globalThis.fetch) {
  const canonical = _canonicalLanguage(language);
  if (!canonical) throw new Error('unknown interface language');
  if (CATALOGS.has(canonical)) return CATALOGS.get(canonical);
  if (typeof fetcher !== 'function') {
    if (canonical === 'en') return CATALOGS.get('en');
    throw new Error('catalog loader unavailable');
  }
  const response = await fetcher(`/static/locales/${encodeURIComponent(canonical)}.json`, {
    cache: 'no-store',
    credentials: 'same-origin',
  });
  if (!response?.ok) throw new Error(`could not load ${canonical} catalog`);
  return installCatalog(await response.json());
}

export async function prepareLocalization(settings = {}, fetcher = globalThis.fetch) {
  const requested = _canonicalLanguage(settings.language) || 'en';
  try {
    await loadCatalog(requested, fetcher);
    configureLocalization({ ...settings, language: requested });
    _cacheLocalizationSettings({ ...settings, language: requested });
    translateDocument();
    return { language: requested, fallback: false };
  } catch (error) {
    configureLocalization({ ...settings, language: 'en' });
    translateDocument();
    const detail = { requested, fallback: 'en', message: error?.message || 'catalog unavailable' };
    _dispatch('alles:localization-error', detail);
    return { language: 'en', fallback: true, error: detail.message };
  }
}

